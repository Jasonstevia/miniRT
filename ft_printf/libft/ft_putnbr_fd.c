#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	i;

	i = n;
	if (i < 0)
	{
		i = -i;
		write(fd, "-", 1);
	}
	if (i >= 10)
		ft_putnbr_fd(i / 10, fd);
	i = i % 10 + '0';
	write(fd, &i, 1);
}

